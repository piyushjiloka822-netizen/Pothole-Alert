  /**
   * Initialize the i18n system
   */
  init() {
    const saved = localStorage.getItem('mcl_lang');
    if (saved && this.translations[saved]) {
      this.currentLang = saved;
    }
    // Set language selector value
    const langSelect = document.querySelector('.lang-select');
    if (langSelect) langSelect.value = this.currentLang;

    // Sync custom language switcher dropdown
    const langCurrentName = document.getElementById('lang-current-name');
    if (langCurrentName && this.langMeta[this.currentLang]) {
      langCurrentName.textContent = this.langMeta[this.currentLang].native;
    }
    document.querySelectorAll('.lang-dropdown-item').forEach(item => {
      item.classList.toggle('active', item.dataset.lang === this.currentLang);
    });

    // Apply language attributes
    this._applyLangAttributes(this.currentLang);
    this.translatePage();
  },

  /**
   * Get a translated string by key — falls back to English
   */
  t(key) {
    const dict = this.translations[this.currentLang];
    return dict && dict[key] ? dict[key] : (this.translations.en[key] || key);
  },

  /**
   * Switch language and re-translate the page
   */
  setLang(lang) {
    if (!this.translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('mcl_lang', lang);

    // Update dropdown
    const langSelect = document.querySelector('.lang-select');
    if (langSelect) langSelect.value = lang;

    // Update custom language selector UI
    const langCurrentName = document.getElementById('lang-current-name');
    if (langCurrentName && this.langMeta[lang]) {
      langCurrentName.textContent = this.langMeta[lang].native;
    }

    // Apply language attributes (lang, dir)
    this._applyLangAttributes(lang);
    this.translatePage();
  },

  /**
   * Apply HTML lang and dir attributes based on selected language
   */
  _applyLangAttributes(lang) {
    const meta = this.langMeta[lang];
    if (!meta) return;
    document.documentElement.lang = meta.lang;
    document.documentElement.dir = meta.dir;
    // Toggle RTL class on body for CSS hooks
    if (meta.dir === 'rtl') {
      document.body.classList.add('rtl');
    } else {
      document.body.classList.remove('rtl');
    }
  },

  /**
   * Translate all elements with data-i18n attribute
   */
  translatePage() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (text) {
        // For inputs with placeholder
        if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
          el.placeholder = text;
        }
        // For select options
        else if (el.tagName === 'OPTION') {
          el.textContent = text;
        }
        // For textarea
        else if (el.tagName === 'TEXTAREA' && el.hasAttribute('placeholder')) {
          el.placeholder = text;
        }
        // For everything else
        else {
          el.textContent = text;
        }
      }
    });

    // Also handle data-i18n-placeholder specifically
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.t(key);
      if (text) el.placeholder = text;
    });

    // Handle data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const text = this.t(key);
      if (text) el.title = text;
    });

    // Handle data-i18n-html (for elements that need innerHTML)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const text = this.t(key);
      if (text) el.innerHTML = text;
    });
  }
